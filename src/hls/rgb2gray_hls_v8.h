#ifndef RGB2GRAY_HLS_V8_H
#define RGB2GRAY_HLS_V8_H

// 支持的最大图像尺寸（VGA），超出会越界
#define MAX_W 640
#define MAX_H 480
#define MAX_PIXELS (MAX_W * MAX_H)

// ---------------------------------------------------------------- 工作模式
// mode 的编码（v8 重新划分，原因见下）：
//
//   bit 0..3  op      算子号（0..9）
//   bit 4     AGC     驱动侧标志：PL 不看，PL 永远按 gain 寄存器乘
//   bit 5     SIGMA   驱动侧标志：告诉驱动「这次要读返回的 sigma」
//
// 为什么把 AGC 从 bit 3 挪到 bit 4：
//   v7 用 mode&7 = 算子、mode&8 = AGC，算子就被锁死在 0..7。
//   v8 要加算子 8、9，AGC 必须让位。
//   PL 侧其实**不需要** AGC 标志 —— 它永远执行 out = clamp((x*gain)>>8)，
//   gain=256 时 (x*256)>>8 == x 严格直通。AGC 开不开由驱动给不给 gain 决定。
//   所以这个位纯粹是给驱动自己记的，挪走没有行为风险。
//
// 回归安全：v8 在 gain=256 下，op=0..7 的输出与 v7 **逐字节一致**
//   （同一套行缓存 + 滑窗 + 同一套边界语义），validate 的 120 组仍然有效。

#define MODE_GRAY    0   // 直通（灰度化在 ARM 侧做）
#define MODE_SOBEL   1   // Sobel 边缘      |gx|+|gy|
#define MODE_EMBOSS  2   // 浮雕            右下 - 左上 + 128
#define MODE_GAUSS   3   // 3x3 高斯        [1 2 1;2 4 2;1 2 1]/16   （v5 遗产，保留）
#define MODE_SHARPEN 4   // 锐化            [0 -1 0;-1 5 -1;0 -1 0]
#define MODE_LAPLACE 5   // 拉普拉斯        [-1 -1 -1;-1 8 -1;-1 -1 -1]
#define MODE_BINARY  6   // 二值化          中心 >= 128 ? 255 : 0
#define MODE_MEAN    7   // 均值模糊        3x3 全 1 / 9

// ---- v8 新增 ----
#define MODE_DIR     8   // 梯度方向量化    0/1/2/3 -> 0/85/170/255，可直视

// ---- v8.1 新增 / v8.2 重构：四级融合流水线（2026-10-29）----
//
// 为什么这三个要独立走 5x5 通路，而不是塞进现有 3x3 主循环：
//     NMS 需要比较中心像素和**沿梯度方向两个邻居**的幅值，
//     而邻居的幅值各自需要 3x3 -> 合起来就是 5x5 感受野。
//     如果把现有主循环的滑窗扩成 5x5，边界语义会从"最外一圈 0"
//     变成"最外四圈 0"，**223 组板端回归全部作废**。
//     所以另开一条通路，现有 op 0..8 一个字节都不动。
//
// v8.2：这三个 op 不再是三个并列算子，而是**同一条流水线的三个抽头**：
//
//     输入灰度
//       │ 级1  AGC + 5x5 可分离高斯（横 5 抽头 → 4 块行缓存 → 纵 5 抽头）
//       │ 级2  Sobel 幅值 + 方向量化（9 个 Sobel 共用 5x5 窗口）
//       │ 级3  非极大值抑制 NMS
//       │ 级4  双阈值 + 滞后
//       ▼
//     输出
//
//   四级在硬件上**全部**都在跑（op 是运行时变量，HLS 不会省任何一级），
//   op 只决定从哪一级抽头把结果写回 DDR。
//
//   抽头 A (op 9)  = 级1 的输出 —— 5x5 二项式高斯去噪图
//   抽头 B (op 11) = 级3 的输出 —— 细化后的幅值（中间结果，可直视）
//   抽头 C (op 10) = 级4 的输出 —— 0/255 边缘，这才是完整的 Canny
//
// 为什么必须融合成一条链，而不是让驱动跑两趟（GAUSS5 再 CANNY）：
//   两趟 = 两次全图访存 + 一次 DDR 往返 = 6.1 ms。
//   融合后一趟 3.07 ms 出边缘，中间结果根本不出片。
//   答辩问"你的 Canny 是单趟吗" —— 现在答案是"是，四级流水，一趟"。
#define MODE_GAUSS5  9   // 抽头 A：级1 输出，5x5 二项式高斯 [1,4,6,4,1]⊗[1,4,6,4,1]/256
#define MODE_CANNY  10   // 抽头 C：级4 输出，完整 Canny 边缘（0/255）
#define MODE_NMS    11   // 抽头 B：级3 输出，NMS 细化后的幅值

// 最后一个**真正实现**的算子号。测试台用它当循环上界，驱动用它做参数校验。
//   加新算子时**必须同步改这里** —— 否则会重演 v8 第一版的老问题：
//   测试台把没实现的 op 也算进去，DUT 落到 else 的 MEAN 分支、
//   黄金参考落到 default 的 0，每一例都假失败，白折腾一轮 csim。
//
// 关于 5x5 高斯（原计划的 D3）：**没有做成 PL 算子**。
//   理由写在 .cpp 顶部：5x5 窗口会改边界语义（外一圈 0 -> 外两圈 0），
//   让全部既有算子的输出改变、120 组板端回归作废，
//   且 25 项 adder tree 会往关键路径加 2~3 ns，威胁 v7 收敛到的 WNS +0.667 ns。
//   改由**驱动侧级联**实现：MODE_GAUSS 连跑两遍，等效 5x5 二项式
//   （[1,4,6,4,1]⊗[1,4,6,4,1]/256），σ 从 0.85 抬到 1.2，零 HLS 改动。
#define MODE_MAX_IMPL MODE_NMS

#define FLAG_AGC   16    // bit 4
#define FLAG_SIGMA 32    // bit 5

#define GAIN_UNITY 256   // Q8.8 的 1.0x

// ---- Canny 双阈值（打包进 thresh 寄存器）----
//   thresh = (HIGH << 8) | LOW，两个都是 0..255
//   Canny 原论文推荐 HIGH:LOW = 2:1 ~ 3:1，这里取 2:1。
//
// 为什么阈值要能由 ARM 每帧改写，而不是写死在 PL 里：
//   这是「AG-Canny」里第二个 A —— 除了 AGC（光照自适应），
//   边缘阈值也应该跟着**实测噪声**走：噪声大 -> 阈值抬高，噪声小 -> 阈值降低。
//   σ 由 PL 每帧实测（op 1..8 的返回值），ARM 拿到后算
//       HIGH = clamp(k_hi * sigma),  LOW = clamp(k_lo * sigma)
//   下一帧写进 thresh 寄存器。闭环是「上一帧的噪声 -> 这一帧的阈值」，
//   和 AGC「上一帧的均值 -> 这一帧的增益」完全同一个套路。
//
// AGC 之后图像被归一化过（暗场景被整体抬亮），所以阈值作用在
//   **归一化后的梯度**上是稳定的 —— 这正是固定阈值也能工作的原因，
//   自适应只是让它更好。
#define CANNY_THRESH_DEFAULT  ((60 << 8) | 30)
#define THRESH_PACK(hi, lo)   (((hi) << 8) | (lo))
#define THRESH_LOW(t)         ((t) & 0xFF)
#define THRESH_HIGH(t)        (((t) >> 8) & 0xFF)

// ---- σ 累加器的 bank 数（2026-10-29 为修性能引入）----
// 必须是 2 的幂，掩码 = 个数 - 1。
// 16 的来历：32 位加法约 2~3 ns，给它 16 拍（160 ns）余量绰绰有余，
// HLS 就能把主循环流水化到 II=1。再大只是白费寄存器。
// 改这个值不会改变 σ 的结果（整数加法可交换，且各 bank 都不溢出），
//   所以 validate_v8.py 的期望值不用跟着改。
#define SIGMA_BANKS 16
#define SIGMA_MASK  (SIGMA_BANKS - 1)

// ---------------------------------------------------------------- 边界语义
//   op 1..8 ：最外一圈输出恒 0（凑不出完整 3x3 窗口）—— 与 v7 完全相同
//   op 0    ：逐像素算子，不受窗口约束
//   op 9..11：最外**四**圈输出恒 0
//
//   为什么 op 9..11 是四圈（v8.1 是两圈，v8.2 因为多串一级高斯变四圈）：
//     四级各延迟 2 行 2 列，累加起来就是 4 行 4 列：
//       横向卷积 2 列 + 纵向卷积 2 行 + Sobel 窗口 2 行 2 列
//     有效输出区 = 行 [4, H-5] × 列 [4, W-5]。
//     这是**几何必然**，不是偷懒 —— 想少留一圈就得做边界延拓
//     （复制/镜像 padding），那要额外逻辑，收益却是 3% 的边缘像素。
//
//   代价核算（VGA）：损失 307200 → 298304 = 2.9% 的像素。
//     换"一趟出边缘"而不是"两趟 + 一次 DDR 往返"，很划算。
//
//   尺寸兜底：有效区要求 H >= 9 且 W >= 9，更小的图全 0 输出。
//
// ---------------------------------------------------------------- 返回值 sigma（ap_return）
// Immerkær 噪声估计的 PL 侧累加器输出。
//
//   PL 只做逐像素累加：返回值 = Σ |I ⊛ N|，N = [[1,-2,1],[-2,4,-2],[1,-2,1]]
//   ARM 侧再算一次 sqrt 和除法（每帧 1 次）：
//       sigma = sqrt(pi/2) * 返回值 / (6 * (W-2) * (H-2))
//
// 为什么这么划分（和 AGC 完全同一个理由）：
//     累加是每像素一次（一帧 307200 次）-> 放 PL
//     sqrt/除法是每帧一次标量        -> 放 ARM
//   **划分依据是数据率，不是"能在 PL 做就全放 PL"。**
//
// 零额外访存：Laplacian 复用主循环里**已经在手上**的那个 3x3 滑窗，
//   只是换一组系数。不新增行缓存、不新增 DDR 访问。
//
// 窗口里存的是**过了 AGC** 的灰度，所以读到的是"放大后的噪声"。
//   要还原传感器原始噪声：sigma_raw = sigma_pl * 256 / gain
//   （AGC 是纯线性增益，Laplacian 严格按 gain/256 缩放）
//
// 仅 op 1..8 时有效（op 0 是逐像素直通，没有 3x3 窗口可用；
//   op 9..11 走 5x5 通路，累加范围和 3x3 通路不同，统一返回 0 —— 见下）。
//
// op 9..11 的 σ **恒返回 0**（2026-10-29 决定）
//   5x5 窗口让窗口中心滞后 2 行 2 列，最后一行/最后一列凑不出完整 3x3，
//   累加范围是 (W-3)(H-3) 而不是 (W-2)(H-2)，跟 op 1..8 对不上。
//   与其让驱动记住两套分母（一个记错就全错），不如明确返回 0：
//   σ 是**每帧一次的旁路测量**，本来就该用 op 1..8 单独跑一趟，
//   而不是蹭在主算子里。
//
// 顶层函数：
//   in     : 输入图，每像素 1 字节灰度（ARM 侧已做 cvtColor）
//   out    : 输出图，每像素 1 字节
//   width  : 图像宽度（≤ MAX_W）
//   height : 图像高度（≤ MAX_H）
//   mode   : 见上面的编码
//   gain   : Q8.8 定点增益，256 = 1.0x
//   thresh : Canny 双阈值打包 (HIGH<<8)|LOW，仅 op 10 用
//   return : Σ|Laplacian|（仅 op 1..8 有效；其余返回 0）
//
// 为什么 sigma 走 return 而不是指针出参（2026-10-28 实测）
//   指针版 `int *sigma_out` + `s_axilite ... depth=1` 的后果：
//     · cosim 连挂两轮（212-300 / 212-360）
//     · 生成的 xrgb2gray_hw.h **没有这个寄存器**，ARM 根本读不到 -> 特性等于没做
//   改用 return 后，寄存器体现在 XRGB2GRAY_CONTROL_ADDR_AP_RETURN_DATA。
//
// ⚠️ return 会挤占 0x10，把 width/height/mode/gain 往后推一格。
//    **驱动必须用生成头文件里的宏，禁止硬编码偏移。**
//
// ⚠️ v8.1 新增 thresh 参数（2026-10-29），排在 gain 之后。
//    预期偏移：ap_return 0x10 / width 0x18 / height 0x20 / mode 0x28
//              / gain 0x30 / thresh 0x38
//    **但这只是预期** —— 构建完第一件事仍然是 grep 生成的 xrgb2gray_hw.h
//    确认 ADDR_*_DATA（记忆里血泪教训：v8 相对 v7 整体后移一格，
//    用旧驱动配新位流会把 width 写进只读的 σ，画面只对上半部分生效）。
int rgb2gray(unsigned char *in, unsigned char *out,
             int width, int height, int mode, int gain, int thresh);

#endif
